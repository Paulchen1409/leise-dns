  const DICT = { de, en };
  let chosen = null;
  function storage() {
    try { if (typeof localStorage !== 'undefined') return localStorage; } catch { /* private mode */ }
    return null;
  }
  function lang() {
    if (chosen === 'en' || chosen === 'de') return chosen;
    let saved = null;
    try { saved = storage()?.getItem('leise.lang'); } catch { /* ignore */ }
    return saved === 'en' ? 'en' : 'de';
  }
  const locale = () => lang() === 'en' ? 'en-GB' : 'de-DE';
  function t(key, vars) {
    let text = (DICT[lang()] && DICT[lang()][key]) || DICT.de[key] || key;
    if (vars) for (const [name, value] of Object.entries(vars)) text = text.split('{' + name + '}').join(String(value));
    return text;
  }
  // Translates a message from the service. German stays as it is.
  function te(message) {
    let text = String(message ?? '');
    if (!text || lang() !== 'en') return text;
    for (const [pattern, english] of ERRORS) text = text.replace(pattern, english);
    return text;
  }
  function apply(root) {
    const doc = root || global.document;
    if (!doc?.documentElement) return;
    doc.documentElement.lang = lang() === 'en' ? 'en' : 'de';
    doc.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
    doc.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
    doc.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'))); });
    doc.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
    doc.querySelectorAll('[data-i18n-title]').forEach(el => { el.setAttribute('title', t(el.getAttribute('data-i18n-title'))); });
  }
  function setLang(next) {
    if (next !== 'en' && next !== 'de') return;
    chosen = next;
    try { storage()?.setItem('leise.lang', next); } catch { /* ignore */ }
    apply();
    global.document?.documentElement?.dispatchEvent(new Event('leise-lang'));
  }
  // Another window (dashboard or tray popup) changed the language.
  if (typeof global.addEventListener === 'function') {
    global.addEventListener('storage', e => {
      if (e.key !== 'leise.lang') return;
      chosen = null;
      apply();
      global.document?.documentElement?.dispatchEvent(new Event('leise-lang'));
    });
  }
  const api = { t, te, lang, locale, setLang, apply, DICT, ERRORS };
  global.LeiseI18n = api;
  if (typeof module !== 'undefined') module.exports = api;
